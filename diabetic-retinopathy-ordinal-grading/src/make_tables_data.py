"""Data and plan tables of diabetic-retinopathy-ordinal-grading and the matching numbers (paper/numbers_data.tex), from stored files only.
Usage: python make_tables_data.py <diabetic-retinopathy-ordinal-grading dir>"""
import os
import sys

import pandas as pd

R = sys.argv[1]
T = os.path.join(R, "paper", "tables")
os.makedirs(T, exist_ok=True)
m = pd.read_csv(os.path.join(R, "data", "processed", "meta.csv"))
m["part"] = m.dataset + "|" + m.split.where(m.dataset == "DDR", "external")
PART = [("DDR|train", "DDR training"), ("DDR|valid", "DDR validation"), ("DDR|test", "DDR test"), ("DeepDRiD|external", "DeepDRiD (external)")]
rows, nums = [], {}
for key, name in PART:
    q = m[m.part == key]
    c = q.grade.value_counts().reindex(range(5), fill_value=0)
    rows.append("%s & %s & %s & %.1f \\\\" % (name, "{:,}".format(len(q)), " & ".join("%s (%.1f)" % ("{:,}".format(c[k]), 100 * c[k] / len(q)) for k in range(5)),
                                             100 * (q.grade >= 2).mean()))
nums["nDDRTrain"] = "{:,}".format(int((m.part == "DDR|train").sum()))
nums["nDDRVal"] = "{:,}".format(int((m.part == "DDR|valid").sum()))
nums["nDDRTest"] = "{:,}".format(int((m.part == "DDR|test").sum()))
dr = m[m.dataset == "DeepDRiD"]
te = m[m.part == "DDR|test"]
nums["nDRImages"] = "{:,}".format(len(dr))
nums["nDRPatients"] = "{:,}".format(dr.patient.nunique())
nums["nDDRGThreePct"] = "%.1f" % (100 * (te.grade == 3).mean())
nums["nDRGThreePct"] = "%.1f" % (100 * (dr.grade == 3).mean())
nums["nDDRRefPct"] = "%.1f" % (100 * (te.grade >= 2).mean())
nums["nDRRefPct"] = "%.1f" % (100 * (dr.grade >= 2).mean())
open(os.path.join(T, "tab_data.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Images per grade, count (\% of the set). Grade 0: none; 1: mild; 2: moderate; 3: severe non-proliferative; 4: proliferative retinopathy. Referable: grade 2 or more. Ungradable DDR images are excluded.}
\label{tab:data}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrrrrr}
\toprule
Set & Images & Grade 0 & Grade 1 & Grade 2 & Grade 3 & Grade 4 & Referable (\%) \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
reg = pd.read_csv(os.path.join(R, "experiments", "experiment_registry.csv"))
NM = {"resnet50.a1_in1k": "ResNet-50", "convnext_tiny.fb_in1k": "ConvNeXt-T"}
FM = {"ce": "CE", "sord": "SORD", "reg": "REG", "coral": "CORAL", "corn": "CORN"}
rows = []
for s, g in reg.groupby("seed"):
    rows.append("%d & %s & %s & %d \\\\" % (s, ", ".join(NM[x] for x in g.model.unique()), ", ".join(FM[x] for x in g.form.unique()), len(g)))
open(os.path.join(T, "tab_plan.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Registered runs, fixed before training and run in this order. Every run is evaluated on DDR validation, DDR test and DeepDRiD with four views.}
\label{tab:plan}
\begin{tabular}{rllr}
\toprule
Seed & Backbones & Formulations & Runs \\
\midrule
""" + "\n".join(rows) + r"""
\midrule
All & & & %d \\
\bottomrule
\end{tabular}
\end{table}
""" % len(reg))
with open(os.path.join(R, "paper", "numbers_data.tex"), "w", encoding="utf8") as f:
    f.write("% generated by src/make_tables_data.py\n")
    for k, v in sorted(nums.items()):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print("wrote tab_data, tab_plan, numbers_data", nums)
