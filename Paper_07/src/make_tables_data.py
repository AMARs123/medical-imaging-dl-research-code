"""Data and plan tables of Paper 07 and the matching numbers (paper/numbers_data.tex), from stored files only.
Usage: python make_tables_data.py <Paper_07 dir>"""
import os
import sys

import pandas as pd

R = sys.argv[1]
T = os.path.join(R, "paper", "tables")
os.makedirs(T, exist_ok=True)
m = pd.read_csv(os.path.join(R, "data", "processed", "meta.csv"))
m = m[m.ok]
rows, nums = [], {}
for (ds, cam), q in m.groupby(["dataset", "camera"], sort=False):
    lab = q.label
    pos, neg, sus = int((lab == 1).sum()), int((lab == 0).sum()), int((lab == -1).sum())
    split = ", ".join("%s %d" % (s, n) for s, n in q.split.value_counts().items()) if ds == "Chaksu" else "test only"
    unan = "%.1f" % (100 * ((q.n_suspect == 0) | (q.n_suspect == q.n_experts)).mean()) if ds == "Chaksu" else "--"
    rows.append("%s & %s & %d & %d & %d & %s & %s & %s \\\\" % (ds.replace("Chaksu", "Ch\\'ak\\d{s}u").replace("RIMONE", "RIM-ONE DL"),
                                                             cam if ds == "Chaksu" else "--", len(q), pos, neg, str(sus) if ds == "PAPILA" else "--",
                                                             unan, split))
ch = m[m.dataset == "Chaksu"]
for cam in ["Remidio", "Bosch", "Forus"]:
    nums["n" + cam] = "{:,}".format(int((ch.camera == cam).sum()))
nums["nChaksuPos"] = "{:,}".format(int((ch.label == 1).sum()))
nums["nChaksuPosPct"] = "%.1f" % (100 * (ch.label == 1).mean())
nums["nUnanimousPct"] = "%.1f" % (100 * ((ch.n_suspect == 0) | (ch.n_suspect == ch.n_experts)).mean())
nums["nLocoRemidioTrain"] = "{:,}".format(int((ch.camera != "Remidio").sum()))
open(os.path.join(T, "tab_data.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Data sets after cropping. Glaucoma: majority of the five experts (Ch\'ak\d{s}u) or clinical diagnosis (PAPILA) or folder label (RIM-ONE DL). Unanimous: share of images on which all five experts agreed.}
\label{tab:data}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{llrrrrrl}
\toprule
Data set & Camera & Images & Glaucoma & Normal & Suspect & Unanimous (\%) & Split \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
reg = pd.read_csv(os.path.join(R, "experiments", "experiment_registry.csv"))
CN = {"all": "All cameras", "loco_Remidio": "Leave out Remidio", "loco_Bosch": "Leave out Bosch", "loco_Forus": "Leave out Forus",
      "all_n271": "All cameras, 271 images$^\\dagger$"}
rows = []
main_reg = reg[reg.config != "all_n271"]
for c, g in reg.groupby("config", sort=False):
    if c == "all_n271":
        rows.append("\\midrule\nMain design & & & & %d \\\\" % len(main_reg))
    rows.append("%s & %s & %s & %s & %d \\\\" % (CN[c], ", ".join(sorted(g.target.unique())), ", ".join(["ResNet-50" if "resnet" in x else "ConvNeXt-T" for x in g.model.unique()]),
                                               ", ".join(map(str, sorted(g.seed.unique()))), len(g)))
open(os.path.join(T, "tab_plan.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Registered runs. The main design was fixed before training; $^\dagger$: size-matched control added after the main results (Section~\ref{sec:res-gap}).}
\label{tab:plan}
\begin{tabular}{llllr}
\toprule
Configuration & Targets & Backbones & Seeds & Runs \\
\midrule
""" + "\n".join(rows) + r"""
\midrule
All & & & & %d \\
\bottomrule
\end{tabular}
\end{table}
""" % len(reg))
with open(os.path.join(R, "paper", "numbers_data.tex"), "w", encoding="utf8") as f:
    f.write("% generated by src/make_tables_data.py\n")
    for k, v in sorted(nums.items()):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print("wrote", nums)
