"""Data numbers and the data/plan tables of Paper 10, from stored files only: the summary written by prepare_hf.py
(P10_DATA/summary.json: split sizes, official sizes, tumour shares) and experiments/experiment_registry.csv.
Writes paper/numbers_data.tex, paper/tables/tab_data.tex, paper/tables/tab_plan.tex.
Usage: python make_tables_data.py <Paper_10 dir>"""
import json
import os
import sys

import pandas as pd

R = sys.argv[1]
DATA = os.environ.get("P10_DATA", "/var/tmp/data/camelyon17_np")
sm = json.load(open(os.path.join(DATA, "summary.json")))
reg = pd.read_csv(os.path.join(R, "experiments", "experiment_registry.csv"))
T = os.path.join(R, "paper", "tables")
os.makedirs(T, exist_ok=True)
fmt = lambda n: "{:,}".format(int(n))  # noqa: E731
nums = {}
K = {"train": "Train", "id_val": "IdVal", "ood_val": "OodVal", "test": "Test"}
for k, n in K.items():
    assert sm[k]["matches"], "%s size does not match the official WILDS size" % k
    nums["nN" + n] = fmt(sm[k]["n"])
    nums["nTum" + n] = "%.1f" % (100 * sm[k]["tumour_share"])
nums["nStepsPatches"] = fmt(1000 * 128)
nums["nBudgetPct"] = "%.0f" % (100 * 1000 * 128 / sm["train"]["n"])
nums["nRunsFt"] = str(int((reg["mode"] == "finetune").sum()))
nums["nRunsLp"] = str(int((reg["mode"] == "linear").sum()))
nums["nRunsAll"] = str(len(reg))
with open(os.path.join(R, "paper", "numbers_data.tex"), "w", encoding="utf8", newline="\n") as f:
    f.write("% generated by src/make_tables_data.py\n")
    for k in sorted(nums):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, nums[k]))

rows = [("Training", "0, 3, 4", "train"), ("ID validation", "0, 3, 4", "id_val"), ("OOD validation", "1", "ood_val"), ("Test", "2", "test")]
body = "\n".join("%s & %s & %s & %.1f \\\\" % (a, h, fmt(sm[k]["n"]), 100 * sm[k]["tumour_share"]) for a, h, k in rows)
open(os.path.join(T, "tab_data.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\footnotesize
\caption{Camelyon17-WILDS splits used here (official WILDS splits; sizes checked against the benchmark paper). Hospitals are numbered as in WILDS. Tumour: share of patches with tumour in the centre region, in percent.}
\label{tab:data}
\begin{tabular}{llrr}
\toprule
Split & Hospitals & Patches & Tumour (\%) \\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\end{table}
""")
g = reg.groupby(["group", "backbone", "aug", "mode"]).seed.agg(["count", "min", "max"]).reset_index()
NM = {"r50_imagenet": "ResNet-50, ImageNet", "r50_lunit": "ResNet-50, pathology (SwAV)", "vits_imagenet": "ViT-S/16, ImageNet",
      "vits_lunit": "ViT-S/16, pathology (DINO)"}
lines = ["%s & %s & %s & %s & %d--%d \\\\" % ({"FT": "Fine-tuning", "LP": "Linear probe"}[r["group"]], NM[r.backbone], {"none": "base", "hed": "base + HED"}[r.aug],
                                             r["count"], r["min"], r["max"]) for _, r in g.iterrows()]
open(os.path.join(T, "tab_plan.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\footnotesize
\caption{Registered runs (%d in total), fixed before any run. Base augmentation: flips and rotations by multiples of $90^\circ$; HED: stain augmentation of Eq.~\ref{eq:hed} in addition.}
\label{tab:plan}
\begin{tabular}{lllrr}
\toprule
Group & Backbone and weights & Augmentation & Runs & Seeds \\
\midrule
""" % len(reg) + "\n".join(lines) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
print("wrote numbers_data.tex, tab_data, tab_plan", nums)
