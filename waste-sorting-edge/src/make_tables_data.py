"""Data and plan tables of waste-sorting-edge and the matching numbers (paper/numbers_data.tex), from stored files only.
Usage: python make_tables_data.py <waste-sorting-edge dir>"""
import os
import sys

import pandas as pd

R = sys.argv[1]
T = os.path.join(R, "paper", "tables")
os.makedirs(T, exist_ok=True)
CLASSES = ["cardboard", "glass", "metal", "paper", "plastic"]
m = pd.read_csv(os.path.join(R, "data", "processed", "meta.csv"))
rows, nums = [], {}
for src, key in [("TrashNet", "TN"), ("TACO", "TA")]:
    q = m[m.source == src]
    c = q.label.value_counts().reindex(range(5), fill_value=0)
    rows.append("%s & %s & %s & %s \\\\" % (src, "{:,}".format(len(q)), " & ".join("%d (%.1f)" % (c[k], 100 * c[k] / len(q)) for k in range(5)),
                                         "{:,}".format(q.group.nunique())))
    nums["n%sImages" % key] = "{:,}".format(len(q))
    nums["n%sPlasticPct" % key] = "%.1f" % (100 * (q.label == 4).mean())
nums["nTAPhotos"] = "{:,}".format(m[m.source == "TACO"].group.nunique())
open(os.path.join(T, "tab_data.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Images per material, count (\% of the source). For TACO, images are object crops and photographs are the scenes they come from.}
\label{tab:data}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lrrrrrrr}
\toprule
Source & Images & Cardboard & Glass & Metal & Paper & Plastic & Photographs \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
reg = pd.read_csv(os.path.join(R, "experiments", "experiment_registry.csv"))
NM = {"mobilenetv3_small_100.lamb_in1k": "MobileNetV3-S", "mobilenetv3_large_100.ra_in1k": "MobileNetV3-L", "efficientnet_b0.ra_in1k": "EfficientNet-B0",
      "resnet18.a1_in1k": "ResNet-18", "resnet50.a1_in1k": "ResNet-50", "convnext_tiny.fb_in1k": "ConvNeXt-T"}
SN = {"trashnet": "TrashNet", "taco": "TACO", "both": "Both"}
rows = []
for t, g in reg.groupby("train_on", sort=False):
    rows.append("%s & %s & %s & %d \\\\" % (SN[t], ", ".join(NM[x] for x in g.model.unique()), ", ".join(map(str, sorted(g.seed.unique()))), len(g)))
open(os.path.join(T, "tab_plan.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\small
\caption{Registered runs, fixed before training.}
\label{tab:plan}
\begin{tabular}{l>{\raggedright\arraybackslash}p{9.5cm}lr}
\toprule
Training sources & Backbones & Seeds & Runs \\
\midrule
""" + "\n".join(rows) + r"""
\midrule
All & & & %d \\
\bottomrule
\end{tabular}
\end{table}
""" % len(reg))
with open(os.path.join(R, "paper", "numbers_data.tex"), "w", encoding="utf8") as f:
    f.write("% generated by src/make_tables_data.py\n")
    for k, v in sorted(nums.items()):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print("wrote", nums)
