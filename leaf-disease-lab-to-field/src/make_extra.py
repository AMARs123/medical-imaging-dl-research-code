"""Supplementary table of leaf-disease-lab-to-field (paper/tables/tab_extra.tex) and its numbers (paper/numbers_extra.tex): macro-F1 and ECE on
PlantDoc and accuracy on the official PlantDoc test split for every condition, from results/processed/runs.csv; with CHECK lines
for the statements of the text. Usage: python make_extra.py <leaf-disease-lab-to-field dir>"""
import os
import sys

import pandas as pd
from scipy.stats import spearmanr

R = sys.argv[1]
r = pd.read_csv(os.path.join(R, "results", "processed", "runs.csv"), keep_default_na=False, na_values=[""])
r = r[r.split == "leaf"]
K = ["model", "source", "aug", "fewshot", "freeze"]
MN = {"resnet50.a1_in1k": "ResNet-50", "efficientnet_b0.ra_in1k": "EfficientNet-B0", "convnext_tiny.fb_in1k": "ConvNeXt-T",
      "vit_small_patch14_dinov2.lvd142m": "DINOv2 ViT-S"}
SRC = {"color": "colour", "segmented": "segmented", "mixed": "mixed"}
checks, nums = [], {}


def check(ok, msg):
    if not ok:
        checks.append(msg)
        print("CHECK:", msg)


a = r[r.set == "pd_all"].groupby(K).agg(acc=("acc", "mean"), f1=("macro_f1", "mean"), ece=("ece", "mean"), n=("seed", "nunique")).reset_index()
t = r[r.set == "pd_test"].groupby(K).agg(acc_test=("acc", "mean"), n_test=("n", "first")).reset_index()
m = a.merge(t, on=K, how="left")
m = m.sort_values(["model", "freeze", "fewshot", "source", "aug"], key=lambda s: s.map(list(MN).index) if s.name == "model" else s)
rows, last = [], None
for _, q in m.iterrows():
    if q.model != last:
        rows.append("\\multicolumn{5}{l}{\\textit{%s}} \\\\" % MN[q.model])
        last = q.model
    name = ("linear probe: " if q.freeze else "") + SRC[q.source] + " images" + (", strong aug." if q.aug == "strong" else "") + (", $k=%d$" % q.fewshot if q.fewshot else "")
    rows.append("%s & %.1f & %.1f & %.3f & %.1f \\\\" % (name, 100 * q.acc, 100 * q.f1, q.ece, 100 * q.acc_test))
open(os.path.join(R, "paper", "tables", "tab_extra.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\footnotesize
\caption{Further PlantDoc measures under the leaf split, mean over three seeds: accuracy and macro-F1 in percent and expected calibration error (Eq.~\ref{eq:ece}) on the PlantDoc images not used for training, and accuracy on the official PlantDoc test split (%d images).}
\label{tab:extra}
\begin{tabular}{lcccc}
\toprule
Condition & Acc $\uparrow$ & Macro-F1 $\uparrow$ & ECE $\downarrow$ & Acc, official test $\uparrow$ \\
\midrule
""" % int(m.n_test.iloc[0]) + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
rho = spearmanr(m.acc, m.acc_test).correlation
nums["nOffRho"] = "%.2f" % rho
nums["nOffN"] = str(len(m))
nums["nEceMin"] = "%.2f" % m.ece.min()
nums["nEceMax"] = "%.2f" % m.ece.max()
nums["nOffDiffMax"] = "%.1f" % (100 * (m.acc - m.acc_test).abs().max())
check((m.n == 3).all(), "a condition has fewer than three seeds")
bacc = r[r.set == "pd_all"].groupby(K).bacc.mean().reindex(pd.MultiIndex.from_frame(m[K])).values
check(spearmanr(m.acc, bacc).correlation > 0.9 and spearmanr(m.acc, m.f1).correlation > 0.9,
      "balanced accuracy or macro-F1 no longer rank the conditions like accuracy (discussion: same conclusions)")
check(rho > 0.9, "the official test split no longer ranks the conditions like the main field set (rank correlation <= 0.9)")
DI, CX = "vit_small_patch14_dinov2.lvd142m", "convnext_tiny.fb_in1k"
dft = m[(m.model == DI) & (m.freeze == 0) & (m.fewshot == 0)]
check(dft.ece.min() > 0.3, "a fine-tuned DINOv2 condition without field images now has ECE <= 0.3 (text: badly overconfident)")
check(m.loc[m.ece.idxmin()].fewshot > 0, "the best-calibrated condition is no longer one with field images")
nums["nEceDinoFtMin"] = "%.2f" % dft.ece.min()
nums["nEceDinoLp"] = "%.2f" % m[(m.model == DI) & (m.freeze == 1) & (m.fewshot == 0) & (m.source == "color")].ece.iloc[0]
c20 = m[(m.model == CX) & (m.fewshot == 20)].iloc[0]
d20 = m[(m.model == DI) & (m.fewshot == 20) & (m.freeze == 1)].iloc[0]
nums["nOffCnxTwenty"] = "%.1f" % (100 * c20.acc_test)
nums["nOffDinoLpTwenty"] = "%.1f" % (100 * d20.acc_test)
check(c20.acc_test >= d20.acc_test, "on the official test split the frozen DINOv2 with 20 field images is now ahead of the fine-tuned ConvNeXt-T")
with open(os.path.join(R, "paper", "numbers_extra.tex"), "w", encoding="utf8", newline="\n") as fh:
    fh.write("% generated by src/make_extra.py (do not edit)\n")
    for k in sorted(nums):
        fh.write("\\newcommand{\\%s}{%s}\n" % (k, nums[k]))
print("EXTRA_DONE", nums, "checks failing", len(checks))
