"""Data and plan tables of chest-xray-pneumonia-shift and the matching numbers (paper/numbers_data.tex), from stored files only.
Usage: python make_tables_data.py <chest-xray-pneumonia-shift dir>"""
import os
import sys

import pandas as pd

R = sys.argv[1]
T = os.path.join(R, "paper", "tables")
os.makedirs(T, exist_ok=True)
m = pd.read_csv(os.path.join(R, "data", "processed", "meta.csv"), keep_default_na=False, na_values=[""])
m = m[m.ok]
NAME = {"G": "Guangzhou children (G)", "NA": "NIH adults (NA)", "NP": "NIH children (NP)"}
ROLE = {"G": "training and test", "NA": "training and test", "NP": "test only"}
rows, nums = [], {}
for g in ["G", "NA", "NP"]:
    q = m[m.group == g]
    age = "1--5 (not per image)" if g == "G" else "%.0f (%.0f--%.0f)" % (q.age.median(), q.age.min(), q.age.max())
    rows.append("%s & %s & %s & %s & %s & %.1f & %s & %s \\\\" % (NAME[g], "{:,}".format(len(q)), "{:,}".format(int(q.label.sum())),
                                                                  "{:,}".format(len(q) - int(q.label.sum())), "{:,}".format(q.patient.nunique()),
                                                                  100 * q.label.mean(), age, ROLE[g]))
    k = g.replace("NA", "NA").replace("NP", "NP")
    nums["n%sImages" % k] = "{:,}".format(len(q))
    nums["n%sPos" % k] = "{:,}".format(int(q.label.sum()))
    nums["n%sPatients" % k] = "{:,}".format(q.patient.nunique())
    nums["n%sPrev" % k] = "%.1f" % (100 * q.label.mean())
open(os.path.join(T, "tab_data.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\footnotesize
\caption{The three groups after selection. NIH ages are in years at the image (median and range); NIH children are patients younger than 18 at their first image.}
\label{tab:data}
\setlength{\tabcolsep}{3pt}
\begin{tabular}{lrrrrrll}
\toprule
Group & Images & Pneumonia & Normal & Patients & Prevalence (\%) & Age & Role \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
reg = pd.read_csv(os.path.join(R, "experiments", "experiment_registry.csv"), keep_default_na=False, na_values=[""])
PUR = {"A": "Transfers, base condition", "B": "Strong augmentation and CLAHE", "C": "Second seed of group A"}
rows = []
for ph, g in reg.groupby("phase"):
    rows.append("%s & %s & %d & %s & %s & %s & %d \\\\" % (ph, PUR[ph], g.model.nunique(), "; ".join(sorted(set(g.train_groups.str.replace(",", "+")))),
                                                          "; ".join(sorted(set(g.aug + "/" + g.prep))), ", ".join(map(str, sorted(g.seed.unique()))), len(g)))
open(os.path.join(T, "tab_plan.tex"), "w", encoding="utf8", newline="\n").write(r"""\begin{table}[!htbp]
\centering\footnotesize
\caption{Registered runs (five folds each), fixed before training. Augmentation/contrast: base or strong augmentation; raw or CLAHE images.}
\label{tab:plan}
\begin{tabular}{llrlllr}
\toprule
Group & Purpose & Backbones & Sources & Augmentation/contrast & Seeds & Runs \\
\midrule
""" + "\n".join(rows) + r"""
\midrule
All & & & & & & %d \\
\bottomrule
\end{tabular}
\end{table}
""" % len(reg))
with open(os.path.join(R, "paper", "numbers_data.tex"), "w", encoding="utf8") as f:
    f.write("% generated by src/make_tables_data.py\n")
    for k, v in sorted(nums.items()):
        f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print("wrote tab_data, tab_plan, numbers_data", nums)
