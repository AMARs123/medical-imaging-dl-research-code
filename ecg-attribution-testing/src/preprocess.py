"""Read PTB-XL (100 Hz) and the PTB-XL+ global fiducial points; write arrays for training and attribution analysis.

Usage: python preprocess.py <ecg-attribution-testing dir>
Outputs in data/processed/:
  signals.npy   float32 [N, 12, 1000]  raw millivolt signals (standardisation is done in training, fitted on folds 1-8)
  meta.csv      ecg_id, patient_id, strat_fold, age, sex, validated_by_human, labels (5 superclass columns) ...
  (fiducial points: see fiducials.py)
Label rule (Strodthoff et al. 2021, "diagnostic superclass"): a record gets superclass c if any of its SCP codes with
diagnostic == 1 maps to c (likelihood values are ignored, as in the benchmark). Records with no superclass are dropped.
"""
import ast
import os
import sys

import numpy as np
import pandas as pd

root = sys.argv[1]
raw = os.path.join(root, "data", "raw", "ptb-xl")
plus = os.path.join(root, "data", "raw", "ptb-xl-plus")
out = os.path.join(root, "data", "processed")
os.makedirs(out, exist_ok=True)
SUPER = ["NORM", "MI", "STTC", "CD", "HYP"]
LEADS = ["I", "II", "III", "AVR", "AVL", "AVF", "V1", "V2", "V3", "V4", "V5", "V6"]

import wfdb  # noqa: E402

db = pd.read_csv(os.path.join(raw, "ptbxl_database.csv"), index_col="ecg_id")
scp = pd.read_csv(os.path.join(raw, "scp_statements.csv"), index_col=0)
diag = scp[scp["diagnostic"] == 1]["diagnostic_class"]
codes = db["scp_codes"].apply(ast.literal_eval)
for c in SUPER:
    db[c] = codes.apply(lambda d: int(any(diag.get(k) == c for k in d)))
db["n_super"] = db[SUPER].sum(1)
print("records", len(db), "| without superclass", int((db.n_super == 0).sum()))
db = db[db.n_super > 0].copy()

sig = np.lib.format.open_memmap(os.path.join(out, "signals.npy"), "w+", np.float32, (len(db), 12, 1000))
bad = []
for i, (eid, r) in enumerate(db.iterrows()):
    rec = wfdb.rdrecord(os.path.join(raw, r["filename_lr"]))
    names = [n.upper() for n in rec.sig_name]
    assert names == LEADS, names
    x = rec.p_signal.T.astype(np.float32)
    if x.shape != (12, 1000) or not np.isfinite(x).all():
        bad.append(eid)
        x = np.nan_to_num(x[:, :1000])
    sig[i] = x
    if i % 5000 == 0:
        print("signals", i, flush=True)
sig.flush()
print("records with non-finite or wrong shape:", bad)

keep = ["patient_id", "age", "sex", "height", "weight", "nurse", "site", "device", "recording_date", "validated_by_human",
        "second_opinion", "initial_autogenerated_report", "baseline_drift", "static_noise", "burst_noise", "electrodes_problems",
        "extra_beats", "pacemaker", "strat_fold", "filename_lr", "scp_codes"] + SUPER + ["n_super"]
db[keep].reset_index().to_csv(os.path.join(out, "meta.csv"), index=False)
print("PREPROCESS_DONE", len(db))
